/**
 * SYNTHETIC TRANSACTIONS — 44 fictional records for the July 2026 demo period.
 * Merchant names are used only as recognisable category examples; no real
 * merchant relationship, card, or cardholder is represented.
 *
 * Every figure below is chosen so that the dashboard, review queue, charts and
 * copilot answers all reconcile to the same underlying numbers.
 */

function line(description: string, descriptionAr: string, amountAed: number): ReceiptLine {
  return { description, descriptionAr, amountAed };
}

function receipt(
  reference: string,
  uploadedAt: string,
  merchantOnReceipt: string,
  totalAed: number,
  lines: ReceiptLine[],
  mismatch = false,
): Receipt {
  return {
    reference,
    uploadedAt,
    merchantOnReceipt,
    totalAed,
    // UAE VAT is 5%; the synthetic receipts show it split out of the total.
    vatAed: Math.round((totalAed - totalAed / 1.05) * 100) / 100,
    lines,
    mismatch,
  };
}

function present(
  kind: EvidenceKind,
  label: string,
  labelAr: string,
  reference?: string,
  capturedAt?: string,
): EvidenceItem {
  return { kind, state: "present", label, labelAr, reference, capturedAt };
}

function missing(kind: EvidenceKind, label: string, labelAr: string): EvidenceItem {
  return { kind, state: "missing", label, labelAr };
}

function selfReported(
  kind: EvidenceKind,
  label: string,
  labelAr: string,
  caveat: string,
  caveatAr: string,
): EvidenceItem {
  return { kind, state: "self_reported", label, labelAr, caveat, caveatAr };
}

function approval(
  approver: string,
  approverRole: string,
  approvedAt: string,
  scope: string,
  scopeAr: string,
  reference: string,
): ApprovalRecord {
  return { approver, approverRole, approvedAt, scope, scopeAr, reference };
}

