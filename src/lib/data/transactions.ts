const transactionIndex = new Map(transactions.map((t) => [t.id, t]));

export function getTransaction(id: string): Transaction | undefined {
  return transactionIndex.get(id);
}

export function requireTransaction(id: string): Transaction {
  const transaction = transactionIndex.get(id);
  if (!transaction) throw new Error(`Unknown transaction: ${id}`);
  return transaction;
}
