const employeeIndex = new Map(employees.map((e) => [e.id, e]));
const departmentIndex = new Map(departments.map((d) => [d.id, d]));

export function getEmployee(id: string): Employee {
  const employee = employeeIndex.get(id);
  if (!employee) throw new Error(`Unknown employee: ${id}`);
  return employee;
}

export function getDepartment(id: Department["id"]): Department {
  const department = departmentIndex.get(id);
  if (!department) throw new Error(`Unknown department: ${id}`);
  return department;
}
